#!/usr/bin/env python3
"""Rebuild the artifact index inside README.md.

Opt-in: a top-level folder is listed only if it contains its own README.md.
Everything outside the START/END markers in the root README is left untouched.

    python3 scripts/build_readme.py          # rewrite README.md if needed
    python3 scripts/build_readme.py --check  # exit 1 if README.md is stale
"""
from __future__ import annotations

import datetime as dt
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
START = "<!-- ARTIFACTS:START -->"
END = "<!-- ARTIFACTS:END -->"
SKIP_DIRS = {"scripts", "node_modules"}
MAX_SUMMARY = 240


def url(path: Path) -> str:
    """Relative, URL-encoded path (spaces -> %20, & -> %26)."""
    return quote(path.relative_to(ROOT).as_posix(), safe="/")


def parse_case_study(readme: Path) -> tuple[str, str]:
    """Title = first '# ' heading; summary = first plain-text paragraph after it."""
    lines = readme.read_text(encoding="utf-8").splitlines()
    title = next((l[2:].strip() for l in lines if l.startswith("# ")), readme.parent.name)
    seen_title = not any(l.startswith("# ") for l in lines)
    para: list[str] = []
    for line in lines:
        s = line.strip()
        if not seen_title:
            seen_title = line.startswith("# ")
            continue
        if not s:
            if para:
                break
            continue
        if s.startswith(("#", "![", "[![", "<", "|", ">", "```", "---")):
            if para:
                break
            continue
        para.append(s)
    summary = " ".join(para)
    if len(summary) > MAX_SUMMARY:
        summary = summary[:MAX_SUMMARY].rsplit(" ", 1)[0].rstrip(",;:.") + "…"
    return title, summary.replace("|", "\\|")


def added_date(readme: Path) -> str:
    """Date the folder's README was first committed (falls back to today)."""
    try:
        out = subprocess.run(
            ["git", "log", "--diff-filter=A", "--format=%as", "--", str(readme.relative_to(ROOT))],
            cwd=ROOT, capture_output=True, text=True, check=True,
        ).stdout.split()
        if out:
            return out[-1]  # git prints newest first
    except (subprocess.CalledProcessError, FileNotFoundError):
        pass
    return dt.date.today().isoformat()


def collect(folder: Path) -> dict:
    title, summary = parse_case_study(folder / "README.md")
    return {
        "title": title,
        "summary": summary,
        "folder": folder,
        "added": added_date(folder / "README.md"),
    }


def render(items: list[dict]) -> str:
    header = "<!-- auto-generated by scripts/build_readme.py; edit each folder's README.md instead -->"
    if not items:
        return f"{header}\n_No artifacts yet._"
    lines = []
    for it in sorted(items, key=lambda i: (i["added"], i["title"].lower()), reverse=True):
        line = f'- **[{it["title"]}]({url(it["folder"])}/)**'
        if it["summary"]:
            line += f' — {it["summary"]}'
        lines.append(f'{line} *(added {it["added"]})*')
    return header + "\n" + "\n".join(lines)


def main() -> int:
    check = "--check" in sys.argv[1:]
    folders = [
        p for p in ROOT.iterdir()
        if p.is_dir() and not p.name.startswith(".") and p.name not in SKIP_DIRS
        and (p / "README.md").is_file()
    ]
    block = render([collect(f) for f in folders])
    text = README.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        print(f"ERROR: README.md must contain {START} and {END}", file=sys.stderr)
        return 2
    new = pattern.sub(lambda _m: f"{START}\n{block}\n{END}", text)
    if new == text:
        print("README.md already up to date")
        return 0
    if check:
        print("README.md is stale")
        return 1
    README.write_text(new, encoding="utf-8")
    print(f"README.md updated ({len(folders)} artifact(s) listed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
